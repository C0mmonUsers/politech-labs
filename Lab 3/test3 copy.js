// ЗАВДАННЯ 2. Булева функція f(x, y, z) для варіанту 5
// Варіант 5 має дві формули: f1 і f2
// ============================================================

// Допоміжна функція XOR (⊕): true, якщо значення різні
const xor = (a, b) => a !== b;

// Формула 1: f = ¬x ∧ ((¬y ∧ z) ∨ x ∨ y)
const f1 = (x, y, z) => !x && ((!y && z) || x || y);

// Формула 2: f = (((x ∧ ¬z) ∨ ¬y) ⊕ ¬(z ∨ ¬x)) ∨ y
const f2 = (x, y, z) => xor((x && !z) || !y, !(z || !x)) || y;

// Аналізує функцію і виводить 4 результати: таблиця, вектор, номер, набори з f=1
function analyze(name, f) {
  console.log(`\n===== ${name} =====`);
  console.log("x y z | f");

  const vector = [];   // вектор значень
  const sets = [];     // набори, на яких f = 1

  // Набори перебираємо від 000 до 111 (номер набору = двійкове число xyz)
  for (let i = 0; i < 8; i++) {
    const x = (i >> 2) & 1;   // старший біт
    const y = (i >> 1) & 1;
    const z = i & 1;          // молодший біт

    const result = Number(f(x, y, z));   // true → 1, false → 0
    vector.push(result);
    if (result === 1) sets.push(i);

    console.log(`${x} ${y} ${z} | ${result}`);
  }

  // 1) Таблиця істинності — вже виведена вище

  // 2) Вектор значень
  console.log("\n2) Вектор значень:", vector.join(""));

  // 3) Порядковий номер: вектор читаємо як двійкове число
  //    з останнього набору до першого (тобто сума f_i * 2^i)
  let number = 0;
  for (let i = 0; i < 8; i++) {
    number += vector[i] * 2 ** i;
  }
  console.log("3) Порядковий номер:", number);

  // 4) Номери наборів, на яких f = 1
  console.log("4) Набори, на яких f = 1:", sets.join(", "));
}

console.log("\n\nЗАВДАННЯ 2. Задати функцію (варіант 5)");
analyze("f1 = ¬x ∧ ((¬y ∧ z) ∨ x ∨ y)", f1);
analyze("f2 = (((x ∧ ¬z) ∨ ¬y) ⊕ ¬(z ∨ ¬x)) ∨ y", f2);

